    /** 新建带抗锯齿等渲染提示的 Graphics2D。 */
    public static Graphics2D newGraphics(BufferedImage img) {
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setRenderingHint(RenderingHints.KEY_FRACTIONALMETRICS, RenderingHints.VALUE_FRACTIONALMETRICS_OFF);
        g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BILINEAR);
        return g;
    }

    /** 带透明度的颜色。 */
    public static Color alpha(Color c, int a) {
        return new Color(c.getRed(), c.getGreen(), c.getBlue(), Math.max(0, Math.min(255, a)));
    }

    /**
     * 圆角矩形填充，坐标语义与 PIL {@code rounded_rectangle} 一致：右下角点也是「包含」的，
     * 所以宽高要 +1（PIL 的 box 是闭区间）。
     */
    public static void rounded(Graphics2D g, double x1, double y1, double x2, double y2, double r, Color fill) {
        fillShape(g, new RoundRectangle2D.Double(x1, y1, x2 - x1 + 1, y2 - y1 + 1, r * 2, r * 2), fill);
    }

    /**
     * 以「替换」语义填充形状：PIL 在 RGBA 图层上画形状是直接覆盖像素，alpha 不与下层叠加。
     * 只有最后把图层整体合成到背景时才会混合，这样半透明卡片/色条的颜色才和 Python 版一致。
     */
    public static void fillShape(Graphics2D g, Shape shape, Color fill) {
        Composite old = g.getComposite();
        g.setComposite(AlphaComposite.Src);
        g.setColor(fill);
        g.fill(shape);
        g.setComposite(old);
    }

    /** 以「替换」语义描边形状（同 {@link #fillShape}）。 */
    public static void strokeShape(Graphics2D g, Shape shape, Color color, Stroke stroke) {
        Composite old = g.getComposite();
        g.setComposite(AlphaComposite.Src);
        g.setColor(color);
        g.setStroke(stroke);
        g.draw(shape);
        g.setComposite(old);
    }

    /** 以「替换」语义贴图（头像等）。 */
    public static void drawImageSrc(Graphics2D g, BufferedImage image, int x, int y, int w, int h) {
        Composite old = g.getComposite();
        g.setComposite(AlphaComposite.Src);
        g.drawImage(image, x, y, w, h, null);
        g.setComposite(old);
    }

    /** 新建透明图层，等价于 Python 版的 {@code ov = Image.new("RGBA", ...)}。 */
    public static BufferedImage newOverlay(int w, int h) {
        return new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
    }

    /**
     * 把透明图层按 SrcOver 合成到底图上，并转成不含 alpha 的 RGB（与 Python 版
     * {@code alpha_composite(...).convert("RGB")} 一致），返回新图。
     */
    public static BufferedImage composite(BufferedImage base, BufferedImage overlay) {
        int w = base.getWidth();
        int h = base.getHeight();
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_RGB);
        Graphics2D g = out.createGraphics();
        g.drawImage(base, 0, 0, null);
        g.drawImage(overlay, 0, 0, null);
        g.dispose();
        return out;
    }

    /**
     * 按 PIL 风格的锚点绘制文本。
     *
     * @param anchor 两个字符：水平 l/m/r + 垂直 a(顶) / m(中) / b(基线)，比如 "la"、"mm"、"ra"、"rm"
     */
    public static void text(Graphics2D g, double x, double y, String s,
                            Font f, Color fill, String anchor) {
        if (s == null || s.isEmpty()) {
            return;
        }
        g.setFont(f);
        g.setColor(fill);
        FontMetrics fm = g.getFontMetrics(f);
        int sw = fm.stringWidth(s);

        double tx = x;
        char h = anchor == null || anchor.isEmpty() ? 'l' : anchor.charAt(0);
        if (h == 'm') {
            tx -= sw / 2.0;
        } else if (h == 'r') {
            tx -= sw;
        }

        double ty;
        char v = anchor == null || anchor.length() < 2 ? 'a' : anchor.charAt(1);
        if (v == 'm') {
            ty = y + (fm.getAscent() - fm.getDescent()) / 2.0;
        } else if (v == 'b') {
            ty = y;
        } else {
            ty = y + fm.getAscent();
        }
        g.drawString(s, (float) tx, (float) ty);
    }

    /** 千分位整数格式化，对标 Python {@code "{:,}".format(int(n))}。 */
    public static String fmtInt(Object n) {
        if (n == null) {
            return "-";
        }
        try {
            long v;
            if (n instanceof Number num) {
                v = num.longValue();
            } else {
                v = (long) Double.parseDouble(String.valueOf(n).trim());
            }
            return String.format(Locale.US, "%,d", v);
        } catch (RuntimeException e) {
            return String.valueOf(n);
        }
    }

    /** 百分比（与 Python 版一致：数值先 /100 再格式化成两位小数百分比）。 */
    public static String pct(Object ratio) {
        return String.format(Locale.US, "%.2f%%", num(ratio, 0) / 100.0);
    }

    /** 从统计项列表里按 {@code ReplyTextItemID} 取 Content，缺失返回 "-"。 */
    public static String statItem(List<Map<String, Object>> items, int id) {
        if (items == null) {
            return "-";
        }
        for (Map<String, Object> item : items) {
            if (item == null) {
                continue;
            }
            if ((int) num(item.get("ReplyTextItemID"), -1) == id) {
                Object content = item.get("Content");
                if (content != null) {
                    String s = String.valueOf(content);
                    if (!s.isEmpty()) {
                        return s;
                    }
                }
            }
        }
        return "-";
    }

    static double num(Object o, double def) {
        if (o instanceof Number n) {
            return n.doubleValue();
        }
        if (o == null) {
            return def;
        }
        try {
            return Double.parseDouble(String.valueOf(o).trim());
        } catch (RuntimeException e) {
            return def;
        }
    }

    static String str(Object o) {
        return o == null ? "" : String.valueOf(o);
    }

    static Map<String, Object> orEmpty(Map<String, Object> m) {
        return m == null ? Map.of() : m;
    }

