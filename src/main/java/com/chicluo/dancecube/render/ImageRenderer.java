    private static Font[] fontsFor(int rowH) {
        if (rowH >= 46) {
            return new Font[]{font(F_REG, 23), font(F_BOLD, 24), font(F_REG, 18),
                    font(F_BOLD, 17), font(F_LIGHT, 17), font(F_BOLD, 22)};
        }
        if (rowH >= 38) {
            return new Font[]{font(F_REG, 21), font(F_BOLD, 22), font(F_REG, 18),
                    font(F_BOLD, 16), font(F_LIGHT, 16), font(F_BOLD, 20)};
        }
        return new Font[]{font(F_REG, 19), font(F_BOLD, 19), font(F_REG, 16),
                font(F_BOLD, 15), font(F_LIGHT, 15), font(F_BOLD, 18)};
    }

    private static boolean startsWithAny(String s, String... prefixes) {
        for (String p : prefixes) {
            if (s.startsWith(p)) {
                return true;
            }
        }
        return false;
    }

    private static Color diffColor(String diffName) {
        for (Map.Entry<String, Color> e : DIFF_COLORS.entrySet()) {
            if (diffName.startsWith(e.getKey())) {
                return e.getValue();
            }
        }
        return C_MUTED;
    }

    /**
     * 成绩表：序号 / 曲名 / 定数 / 难度 / ACC / 评级 / 战力条 / 战力。
     */
    public static void drawSongTable(Graphics2D g, List<Score> songs, int top, int rowH, int y0) {
        if (songs == null || songs.isEmpty()) {
            text(g, W / 2.0, y0 + 80, "暂无符合条件的成绩", font(F_REG, 24), C_MUTED, "mm");
            return;
        }
        Font[] fs = fontsFor(rowH);
        Font rowF = fs[0];
        Font numF = fs[1];
        Font accF = fs[2];
        Font lvF = fs[3];
        Font diffF = fs[4];
        Font ratF = fs[5];
        Font gradeF = font(F_BOLD, 15);
        int t = Math.max(1, top);
        FontMetrics nameMetrics = g.getFontMetrics(rowF);

        for (int i = 1; i <= songs.size(); i++) {
            Score s = songs.get(i - 1);
            double cy = y0 + (double) (i - 1) * rowH;
            double mid = cy + rowH / 2.0 - 1;

            text(g, M + 24, mid, String.format(Locale.US, "%02d", i), numF,
                    i > 3 ? C_DIM : C_ACCENT, "lm");

            String name = s.name() == null ? "" : s.name();
            int maxw = 205;
            if (nameMetrics.stringWidth(name) > maxw) {
                while (!name.isEmpty() && nameMetrics.stringWidth(name + "…") > maxw) {
                    // 按码点删，避免把代理对（emoji）劈成两半
                    name = name.substring(0, name.offsetByCodePoints(name.length(), -1));
                }
                name += "…";
            }
            Color nameFill = s.ownerType() == 2 ? DIFF_SHOW : C_TEXT;
            text(g, M + 72, mid, name, rowF, nameFill, "lm");

            int lx = M + 290;
            rounded(g, lx, mid - 12, lx + 46, mid + 12, 8, alpha(C_ACCENT, 38));
            text(g, lx + 23, mid, "Lv" + s.level(), lvF, C_ACCENT, "mm");

            String diffName = s.levelTypeName() == null || s.levelTypeName().isEmpty()
                    ? "-" : s.levelTypeName();
            Color dcol = diffName.startsWith("[S+]") ? DIFF_SHOW : diffColor(diffName);
            int dtx = M + 354;
            if (startsWithAny(diffName, "[初]", "[中]", "[高]", "[S+]", "[秀]")) {
                int dw = g.getFontMetrics(diffF).stringWidth(diffName);
                rounded(g, dtx - 7, mid - 12, dtx + dw + 7, mid + 12, 7, alpha(dcol, 30));
                text(g, dtx, mid, diffName, diffF, dcol, "lm");
            } else {
                text(g, dtx, mid, diffName, diffF, dcol, "lm");
            }

            text(g, M + 470, mid, String.format(Locale.US, "%.2f%%", s.acc()), accF, C_TEXT, "lm");

            String grade = s.grade();
            if (grade != null && !grade.isEmpty()) {
                int gx = M + 572;
                rounded(g, gx, mid - 11, gx + 40, mid + 11, 7, alpha(C_ACCENT2, 45));
                text(g, gx + 20, mid, grade, gradeF, C_ACCENT2, "mm");
            }

            int bx = M + 628;
            int bw = 248;
            int bh = 8;
            double by = mid - bh / 2.0 + 1;
            rounded(g, bx, by, bx + bw, by + bh, 4, new Color(255, 255, 255, 20));
            double fw = Math.max(bh, bw * (double) s.rating() / t);
            rounded(g, bx, by, bx + fw, by + bh, 4, C_ACCENT);

            text(g, W - M - 24, mid, String.valueOf(s.rating()), ratF, C_ACCENT, "rm");
        }
    }

    /**
     * 一张卡片：标题 + 副标题 + 表格，返回卡片底部 y。note 画在标题右侧。
     */
    public static int drawSection(Graphics2D g, int y, String title, String sub,
                                  List<Score> songs, int rowH, int top, String note) {
        int n = songs == null ? 0 : songs.size();
        int h = 66 + n * rowH + 14;
        rounded(g, M, y, W - M, y + h, 20, new Color(255, 255, 255, 16));

        Font titleFont = font(F_BOLD, 27);
        text(g, M + 22, y + 18, title, titleFont, C_TEXT, "la");
        if (note != null && !note.isEmpty()) {
            int tw = g.getFontMetrics(titleFont).stringWidth(title);
            text(g, M + 22 + tw + 18, y + 31, note, font(F_LIGHT, 16), C_DIM, "lm");
        }
        text(g, W - M - 22, y + 24, sub, font(F_LIGHT, 18), C_DIM, "ra");
        drawSongTable(g, songs, top, rowH, y + 66);
        return y + h;
    }

