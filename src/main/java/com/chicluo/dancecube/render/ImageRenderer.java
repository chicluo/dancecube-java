    private static final Map<String, Font> FONT_CACHE = new HashMap<>();
    private static final AtomicBoolean FONT_WARNED = new AtomicBoolean(false);

    private static Path pickFont(List<String> candidates) {
        for (String p : candidates) {
            try {
                Path path = Path.of(p);
                if (Files.isRegularFile(path)) {
                    return path;
                }
            } catch (RuntimeException ignored) {
                // 非法路径（比如系统不允许）直接跳过
            }
        }
        return null;
    }

    /**
     * 取指定字号的字体，带缓存。找不到中文字体时回退 JRE 默认无衬线字体并打印一次警告，
     * 绝不抛异常。
     */
    public static Font font(Path path, int size) {
        String key = (path == null ? "<default>" : path.toString()) + '@' + size;
        synchronized (FONT_CACHE) {
            Font cached = FONT_CACHE.get(key);
            if (cached != null) {
                return cached;
            }
        }
        Font f = loadFont(path, size);
        synchronized (FONT_CACHE) {
            FONT_CACHE.put(key, f);
        }
        return f;
    }

    private static Font loadFont(Path path, int size) {
        if (path != null) {
            // .ttc / .ttf 走 TRUETYPE；.otf(CFF) 某些 JRE 需要 TYPE1 才能读
            for (int type : new int[]{Font.TRUETYPE_FONT, Font.TYPE1_FONT}) {
                try {
                    return Font.createFont(type, path.toFile()).deriveFont((float) size);
                } catch (Exception ignored) {
                    // 换下一种格式或下一个候选
                }
            }
        }
        warnMissingFont();
        return new Font(Font.SANS_SERIF, Font.PLAIN, size);
    }

    private static void warnMissingFont() {
        if (FONT_WARNED.compareAndSet(false, true)) {
            System.err.println("[dancecube-render] 没有找到可用的中文字体，图中的中文会显示成方框。"
                    + " Windows 请确认 C:\\Windows\\Fonts 下有 msyh.ttc / msyhbd.ttc / simhei.ttf；"
                    + " Linux 请安装 fonts-wqy-zenhei 或 fonts-noto-cjk。");
        }
    }

