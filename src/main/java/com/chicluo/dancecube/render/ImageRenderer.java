    /**
     * 战力分析图（单表）。
     *
     * @param snapshot 玩家快照
     * @param songs    要展示的成绩（B15 / B30 / AP30，调用方已排好序并截断）
     * @param mode     {@code b15} / {@code b30} / {@code ap30}，决定标题、副标题与行高
     */
    public static BufferedImage buildAnalysis(PlayerSnapshot snapshot, List<Score> songs, String mode) {
        List<Score> list = songs == null ? List.of() : songs;
        String m = mode == null ? "b15" : mode;
        String title;
        String sub;
        int rowH;
        switch (m) {
            case "b30" -> {
                title = "B30 战力分析";
                sub = String.format(Locale.US, "战力前 30 首 · 仅官谱 · 共 %d 首", list.size());
                rowH = 34;
            }
            case "ap30" -> {
                title = "AP30 满分成绩";
                sub = String.format(Locale.US, "ALL PERFECT · 前 30 首 · 共 %d 首", list.size());
                rowH = 46;
            }
            default -> {
                title = "B15 战力分析";
                sub = String.format(Locale.US, "最佳 15 首 · 仅官谱 · 共 %d 首", list.size());
                rowH = 46;
            }
        }
        return render(snapshot, List.of(new Section(title, sub, list, rowH)), false);
    }

    /**
     * B15 + R15 上下双表（mode=both）。
     */
    public static BufferedImage buildBoth(PlayerSnapshot snapshot, List<Score> b15, List<Score> r15) {
        List<Score> b = b15 == null ? List.of() : b15;
        List<Score> r = r15 == null ? List.of() : r15;
        int bTotal = b.stream().mapToInt(Score::rating).sum();
        int rTotal = r.stream().mapToInt(Score::rating).sum();
        double bAvg = b.isEmpty() ? 0 : bTotal / (double) b.size();
        double rAvg = r.isEmpty() ? 0 : rTotal / (double) r.size();
        List<Section> sections = List.of(
                new Section("B15 战力分析",
                        String.format(Locale.US, "最佳 15 首 · 仅官谱 · 合计 %d · 平均 %.1f", bTotal, bAvg),
                        b, 42),
                new Section("R15 最近游玩",
                        String.format(Locale.US, "最近 15 局 · 01 为最新 · 合计 %d · 平均 %.1f", rTotal, rAvg),
                        r, 42));
        return render(snapshot, sections, true);
    }

    private static BufferedImage render(PlayerSnapshot snapshot, List<Section> sections, boolean both) {
        if (snapshot == null) {
            throw new IllegalArgumentException("snapshot 不能为空");
        }
        Map<String, Object> info = orEmpty(snapshot.info());
        Map<String, Object> account = orEmpty(snapshot.account());

        int top = 1;
        for (Section s : sections) {
            for (Score sc : s.songs()) {
                top = Math.max(top, sc.rating());
            }
        }

        int y = 300;
        for (Section s : sections) {
            y += 66 + s.songs().size() * s.rowH() + 14 + (both ? 20 : 0);
        }
        int histY = y + 4;
        int histH = 286;
        int height = histY + histH + 86;

        BufferedImage img = gradientBg(W, height);
        BufferedImage ov = newOverlay(W, height);
        Graphics2D g = newGraphics(ov);

        drawHeader(g, info);
        drawStats(g, 196, List.of(
                new Stat("积分", fmtInt(info.get("MusicScore"))),
                new Stat("全国排名", fmtInt(info.get("RankNation"))),
                new Stat("全连率", pct(info.get("ComboPercent"))),
                new Stat("游玩次数", statItem(snapshot.statsItems(), 5)),
                new Stat("金币", fmtInt(account.get("Gold")))));

        int yy = 300;
        for (Section s : sections) {
            drawSection(g, yy, s.title(), s.sub(), s.songs(), s.rowH(), top, DISCLAIMER);
            yy += 66 + s.songs().size() * s.rowH() + 14 + (both ? 20 : 0);
        }

        drawHistory(g, histY, histH, snapshot.history());

        String extra = "";
        if (!both) {
            List<Score> first = sections.isEmpty() ? List.of() : sections.get(0).songs();
            int total = first.stream().mapToInt(Score::rating).sum();
            double avg = first.isEmpty() ? 0 : total / (double) first.size();
            extra = String.format(Locale.US, "合计 %d · 平均 %.1f", total, avg);
        }
        drawFooter(g, height, extra);

        g.dispose();
        return composite(img, ov);
    }
