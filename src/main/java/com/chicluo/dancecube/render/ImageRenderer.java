    /**
     * 战力变化折线：按天去重取当天最后一次记录，画折线 + 面积 + 峰值标注。
     * 返回卡片底部 y。
     */
    public static int drawHistory(Graphics2D g, int y, int h, List<Map<String, Object>> hist) {
        rounded(g, M, y, W - M, y + h, 20, new Color(255, 255, 255, 16));
        text(g, M + 22, y + 16, "战力变化", font(F_BOLD, 25), C_TEXT, "la");

        List<Map<String, Object>> list = hist == null ? List.of() : hist;
        Map<String, Integer> byDay = new TreeMap<>();
        for (Map<String, Object> r : list) {
            if (r == null) {
                continue;
            }
            String logTime = r.get("LogTime") == null ? "" : String.valueOf(r.get("LogTime"));
            if (logTime.length() < 10) {
                continue;
            }
            byDay.put(logTime.substring(0, 10), (int) num(r.get("LvRatio"), 0));
        }

        if (byDay.isEmpty()) {
            text(g, W / 2.0, y + h / 2.0, "暂无历史战力", font(F_REG, 22), C_MUTED, "mm");
            return y + h;
        }

        List<String> days = new ArrayList<>(byDay.keySet());
        List<Integer> vals = new ArrayList<>(byDay.values());
        int n = vals.size();

        text(g, W - M - 22, y + 22, String.format(Locale.US, "%s → %s · 当前 %d · %d 次变动",
                        days.get(0).substring(5), days.get(n - 1).substring(5),
                        vals.get(n - 1), list.size()),
                font(F_LIGHT, 17), C_DIM, "ra");

        int cx0 = M + 34;
        int cy0 = y + 62;
        int cw2 = W - 2 * M - 68;
        int ch2 = h - 104;
        int lo = Collections.min(vals);
        int hi = Collections.max(vals);
        double pad = Math.max(8, (hi - lo) * 0.15);
        double loP = lo - pad;
        double hiP = hi + pad;

        java.awt.Stroke gridStroke = new BasicStroke(1f);
        for (int k = 0; k < 4; k++) {
            double gy = cy0 + ch2 * k / 3.0;
            strokeShape(g, new Line2D.Double(cx0, gy, cx0 + cw2, gy),
                    new Color(255, 255, 255, 12), gridStroke);
        }

        double[] xs = new double[n];
        double[] ys = new double[n];
        for (int i = 0; i < n; i++) {
            xs[i] = cx0 + cw2 * (double) i / Math.max(1, n - 1);
            ys[i] = cy0 + ch2 - (vals.get(i) - loP) / Math.max(1e-6, hiP - loP) * ch2;
        }

        Path2D area = new Path2D.Double();
        area.moveTo(xs[0], ys[0]);
        for (int i = 1; i < n; i++) {
            area.lineTo(xs[i], ys[i]);
        }
        area.lineTo(cx0 + cw2, cy0 + ch2);
        area.lineTo(cx0, cy0 + ch2);
        area.closePath();
        fillShape(g, area, alpha(C_ACCENT, 26));

        Path2D line = new Path2D.Double();
        line.moveTo(xs[0], ys[0]);
        for (int i = 1; i < n; i++) {
            line.lineTo(xs[i], ys[i]);
        }
        strokeShape(g, line, C_ACCENT, new BasicStroke(3f, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));

        for (int i : new int[]{0, n - 1}) {
            fillShape(g, new Ellipse2D.Double(xs[i] - 5, ys[i] - 5, 11, 11), C_ACCENT);
        }

        int max = Collections.max(vals);
        int mi = vals.indexOf(max);
        fillShape(g, new Ellipse2D.Double(xs[mi] - 4, ys[mi] - 4, 9, 9), C_ACCENT2);
        text(g, xs[mi], ys[mi] - 14, "峰值 " + max, font(F_BOLD, 16), C_ACCENT2, "mb");

        Font axisFont = font(F_LIGHT, 15);
        text(g, cx0, cy0 + ch2 + 10, days.get(0).substring(5), axisFont, C_DIM, "la");
        text(g, cx0 + cw2, cy0 + ch2 + 10, days.get(n - 1).substring(5), axisFont, C_DIM, "ra");
        return y + h;
    }

