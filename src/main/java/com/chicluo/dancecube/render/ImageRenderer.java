    /**
     * 深色渐变背景 + 三团柔光，复刻 Python 版 {@code gradient_bg}。
     *
     * <p>Python 用 {@code GaussianBlur(120)} 做辉光；AWT 没有内置高斯模糊，
     * 这里用 3 次可分离盒式模糊逼近同一 σ 的高斯模糊（与 PIL 的处理顺序一致：
     * 先在透明图层画三个椭圆，再整体模糊，最后 SrcOver 合成）。</p>
     */
    public static BufferedImage gradientBg(int w, int h) {
        BufferedImage img = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = newGraphics(img);

        g.setColor(C_BG_TOP);
        g.fillRect(0, 0, w, h);
        for (int y = 0; y < h; y++) {
            double t = y / (double) Math.max(1, h - 1);
            g.setColor(new Color(
                    (int) (C_BG_TOP.getRed() + (C_BG_BOT.getRed() - C_BG_TOP.getRed()) * t),
                    (int) (C_BG_TOP.getGreen() + (C_BG_BOT.getGreen() - C_BG_TOP.getGreen()) * t),
                    (int) (C_BG_TOP.getBlue() + (C_BG_BOT.getBlue() - C_BG_TOP.getBlue()) * t)));
            // 用 fillRect 逐行铺满：drawLine 会被抗锯齿摊到相邻两行，导致整体偏暗
            g.fillRect(0, y, w, 1);
        }

        // 三个 ellipse 的坐标与 Python 版逐值一致
        BufferedImage glow = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        Graphics2D gg = newGraphics(glow);
        fillShape(gg, new Ellipse2D.Double(-220, -260, 640, 640), new Color(79, 227, 193, 26));
        fillShape(gg, new Ellipse2D.Double(w - 380, 120, 640, 640), new Color(123, 140, 255, 24));
        fillShape(gg, new Ellipse2D.Double(w - 200, h - 420, 520, 540), new Color(79, 227, 193, 16));
        gg.dispose();

        gaussianBlurArgb(glow, 120);
        g.drawImage(glow, 0, 0, null);

        g.dispose();
        return img;
    }

    /** 对 ARGB 四个通道分别做 3 次盒式模糊，近似 σ 的高斯模糊（PIL GaussianBlur(radius) 的 radius 即 σ）。 */
    private static void gaussianBlurArgb(BufferedImage img, int sigma) {
        int w = img.getWidth();
        int h = img.getHeight();
        int[] px = ((DataBufferInt) img.getRaster().getDataBuffer()).getData();
        int n = px.length;
        byte[][] ch = new byte[4][n];
        for (int i = 0; i < n; i++) {
            int p = px[i];
            ch[0][i] = (byte) (p >>> 24);
            ch[1][i] = (byte) (p >>> 16);
            ch[2][i] = (byte) (p >>> 8);
            ch[3][i] = (byte) p;
        }
        // 3 次盒式模糊的总方差 = 3 * (r(r+1)/3) ≈ σ²
        int r = (int) Math.round((Math.sqrt(4.0 * sigma * sigma + 1) - 1) / 2.0);
        for (int c = 0; c < 4; c++) {
            boxBlur3(ch[c], w, h, r);
        }
        for (int i = 0; i < n; i++) {
            px[i] = ((ch[0][i] & 0xFF) << 24) | ((ch[1][i] & 0xFF) << 16)
                    | ((ch[2][i] & 0xFF) << 8) | (ch[3][i] & 0xFF);
        }
    }

    private static void boxBlur3(byte[] data, int w, int h, int r) {
        byte[] tmp = new byte[data.length];
        for (int pass = 0; pass < 3; pass++) {
            boxBlurH(data, tmp, w, h, r);
            boxBlurV(tmp, data, w, h, r);
        }
    }

    private static void boxBlurH(byte[] src, byte[] dst, int w, int h, int r) {
        int win = 2 * r + 1;
        for (int y = 0; y < h; y++) {
            int row = y * w;
            int sum = 0;
            for (int i = -r; i <= r; i++) {
                sum += src[row + clamp(i, w)] & 0xFF;
            }
            for (int x = 0; x < w; x++) {
                dst[row + x] = (byte) (sum / win);
                sum += (src[row + clamp(x + r + 1, w)] & 0xFF) - (src[row + clamp(x - r, w)] & 0xFF);
            }
        }
    }

    private static void boxBlurV(byte[] src, byte[] dst, int w, int h, int r) {
        int win = 2 * r + 1;
        for (int x = 0; x < w; x++) {
            int sum = 0;
            for (int i = -r; i <= r; i++) {
                sum += src[clamp(i, h) * w + x] & 0xFF;
            }
            for (int y = 0; y < h; y++) {
                dst[y * w + x] = (byte) (sum / win);
                sum += (src[clamp(y + r + 1, h) * w + x] & 0xFF) - (src[clamp(y - r, h) * w + x] & 0xFF);
            }
        }
    }

    private static int clamp(int v, int n) {
        return v < 0 ? 0 : (v >= n ? n - 1 : v);
    }

    /** 表头：头像 + 昵称 + ID/城市/战队 + 右侧大号战力值。 */
    public static void drawHeader(Graphics2D g, Map<String, Object> info) {
        Map<String, Object> m = orEmpty(info);
        int avSize = 96;
        int px = M;
        int py = 44;

        // 头像外圈
        strokeShape(g, new Ellipse2D.Double(px - 4, py - 4, avSize + 9, avSize + 9),
                alpha(C_ACCENT, 110), new BasicStroke(2f));

        String userName = str(m.get("UserName"));
        if (userName.isEmpty()) {
            userName = "舞立方 " + fmtInt(m.get("UserID"));
        }
        BufferedImage avatar = AvatarLoader.load(str(m.get("HeadimgURL")), avSize);
        if (avatar != null) {
            g.drawImage(avatar, px, py, null);
        } else {
            drawAvatarFallback(g, px, py, avSize, userName);
        }

        int tx = px + avSize + 22;
        text(g, tx, 50, userName, font(F_BOLD, 42), C_TEXT, "la");

        List<String> meta = new ArrayList<>();
        meta.add("ID " + fmtInt(m.get("UserID")));
        if (!str(m.get("CityName")).isEmpty()) {
            meta.add(str(m.get("CityName")));
        }
        if (!str(m.get("TeamName")).isEmpty()) {
            meta.add("战队 " + str(m.get("TeamName")));
        }
        text(g, tx, 104, String.join(" · ", meta), font(F_LIGHT, 21), C_MUTED, "la");

        int ratio = (int) num(m.get("LvRatio"), 0);
        text(g, W - M, 44, String.valueOf(ratio), font(F_BOLD, 82), C_ACCENT, "ra");
        text(g, W - M, 136, "LVRATIO", font(F_REG, 17), C_DIM, "ra");
    }

    /** 无网络依赖的头像：3 倍尺寸画圆 + 首字，再缩小，保证边缘平滑。 */
    private static void drawAvatarFallback(Graphics2D g, int x, int y, int size, String name) {
        int s = size * 3;
        BufferedImage tmp = new BufferedImage(s, s, BufferedImage.TYPE_INT_ARGB);
        Graphics2D tg = newGraphics(tmp);
        tg.setColor(new Color(46, 60, 92, 255));
        tg.fillOval(0, 0, s, s);

        String ch = "?";
        if (name != null && !name.isEmpty()) {
            int end = name.offsetByCodePoints(0, 1);
            ch = name.substring(0, end);
        }
        Font f = font(F_BOLD, (int) (size * 1.25));
        tg.setFont(f);
        tg.setColor(new Color(200, 215, 240));
        FontMetrics fm = tg.getFontMetrics(f);
        int tw = fm.stringWidth(ch);
        tg.drawString(ch, (s - tw) / 2f, (s - fm.getHeight()) / 2f + fm.getAscent());
        tg.dispose();

        drawImageSrc(g, tmp, x, y, size, size);
    }

